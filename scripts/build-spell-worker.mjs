/**
 * Bundles the spell-check Web Worker (Hunspell WASM + the Turkish-agnostic
 * engine glue) into a single string module. The library turns that string
 * into a Blob URL at runtime, so consumers need no worker/bundler setup.
 *
 * Output is generated, git-ignored, and rebuilt by the `pre*` npm hooks.
 */
import { build } from "esbuild";
import { writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import path from "node:path";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const dir = path.join(root, "src/components/rich-text/spellcheck");

const result = await build({
  entryPoints: [path.join(dir, "spell-worker.ts")],
  bundle: true,
  format: "iife",
  platform: "browser",
  // hunspell-asm's ESM build calls `import * as nanoid` as a function,
  // which crashes once bundled; its CJS build (with the browser field
  // swapping in the web runtime) is sound.
  mainFields: ["browser", "main"],
  target: "es2020",
  minify: true,
  write: false,
  logLevel: "warning",
  define: { "process.env.NODE_ENV": '"production"' },
});

const code = result.outputFiles[0].text;
await writeFile(
  path.join(dir, "worker-source.generated.ts"),
  "// Generated by scripts/build-spell-worker.mjs — do not edit.\n" +
    `export const SPELL_WORKER_SOURCE: string = ${JSON.stringify(code)};\n`,
);
console.log(`spell worker: ${(code.length / 1024).toFixed(0)} KB`);
